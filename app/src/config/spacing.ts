/**
 * Standard Spacing System (8pt Grid)
 * 
 * Consistent use of spacing improves visual hierarchy, grouping, 
 * and provides perceptual "breathability" to the interface.
 */

export const SPACING = {
  /** 4pt - Tightest - Micro labels, micro gaps between related items */
  SPACE_XXS: 4,
  /** 8pt - Base unit - Content grouping, small margins, form rows */
  SPACE_XS: 8,
  /** 12pt - Tight - Cards items, tighter internal layout */
  SPACE_SM: 12,
  /** 16pt - Standard - Page margins, standard card padding, large form rows */
  SPACE_MD: 16,
  /** 24pt - Loose - Section separation, prominent internal padding */
  SPACE_LG: 24,
  /** 32pt - XL - Major sections, page headers, breathing room */
  SPACE_XL: 32,
  /** 48pt - 2XL - Hero cards, intense separation */
  SPACE_2XL: 48,
  /** 64pt - 3XL - Deep breathability (rarely used) */
  SPACE_3XL: 64,
};
